// Method 1 : length
//
// Definition :
// length is a PROPERTY (not a method) of a string.
// It returns the total number of characters present in
// the string, including spaces and special characters.
// It is commonly used to find the size of a string,
// validate input length (like passwords or usernames),
// and loop through each character of a string.
//
// Syntax : string.length


let name = "Aarushi Jain";
let whitespace = " ";
let specialCharacter = "@!@#$Z%6";
let Empty = "";

console.log('Finding the length of name ' , name.length)
console.log('Finding the length of whitespace ' , whitespace.length)
console.log('Finding the length of specialCharacter ' , specialCharacter.length)
console.log('Finding the length of Empty ' , Empty.length)

